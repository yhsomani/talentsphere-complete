#!/usr/bin/env python3
"""Usage: python3 -I docs/mindmap/tools/enrich.py <workdir> [<results-dir>]

Runs between extract.py and generate.py. Rewrites <workdir>/graph_raw.json and aux.json in place.
Read-only on the repository except for docs/mindmap/master/ID_LEDGER.json.

1. Stable IDs. Every node gets the ID recorded for its logical key in master/ID_LEDGER.json. New
   entities get the next free number for their prefix; entities that disappear keep their number
   reserved (the ledger never reuses an ID). The ledger is seeded from the committed graph the
   first time, so adopting it renumbers nothing.
2. Documentation nodes. The project's own canonical IDs become nodes: F-01..F-173 (feature
   registry), J-01..J-28 (journey registry), BR-01..BR-248 (business-rule registry). Code and
   test files that cite those IDs are linked with IMPLEMENTS / TESTED_BY edges carrying file:line.
3. Execution evidence (optional). <results-dir> may hold JSON reports produced outside the repo:
   vitest.json (vitest --reporter=json), vitest-pg.json (same, pg config), e2e.json (playwright
   --reporter=json) and run.json ({"commit", "date", "commands": {...}}). Results are attached to
   TEST and JOUR nodes as `execution`. Nothing here runs a test.
"""
import json, os, re, sys, glob, subprocess, collections

SCR = sys.argv[1]
RES = sys.argv[2] if len(sys.argv) > 2 else None
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
OUT = os.path.join(ROOT, 'docs', 'mindmap')
os.chdir(ROOT)
G = json.load(open(f'{SCR}/graph_raw.json'))
A = json.load(open(f'{SCR}/aux.json'))


def read(p):
    return open(p, encoding='utf8', errors='replace').read()


# ------------------------------------------------------------------ 1. stable IDs
def first_file(n):
    e = (n.get('evidence') or [{}])[0]
    return e.get('file') or ''


def logical_keys(nodes):
    """type|name|file, plus an ordinal when the same triple occurs more than once (ordered by line)."""
    groups = collections.defaultdict(list)
    for n in nodes:
        groups[(n['type'], n['name'], first_file(n))].append(n)
    keys = {}
    for (t, nm, f), ns in groups.items():
        ns.sort(key=lambda n: ((n.get('evidence') or [{}])[0].get('line') or 0, n['id']))
        for i, n in enumerate(ns):
            keys[n['id']] = f'{t}|{nm}|{f}' + (f'|#{i + 1}' if len(ns) > 1 else '')
    return keys


LEDGER = os.path.join(OUT, 'master', 'ID_LEDGER.json')
if os.path.exists(LEDGER):
    ledger = json.load(open(LEDGER))
else:
    seed = json.load(open(os.path.join(OUT, 'master', 'MASTER_PROJECT_GRAPH.json')))
    seed_nodes = [n for n in seed['nodes'] if re.match(r'^[A-Z]+-\d{3,}$', n['id'])]
    ledger = {'note': 'logical key -> stable node ID. Generated by tools/enrich.py; IDs are never reused.',
              'ids': {key: nid for nid, key in logical_keys(seed_nodes).items()}}

key_of = logical_keys(G['nodes'])
used_numbers = collections.defaultdict(set)
for i in ledger['ids'].values():
    p, num = i.rsplit('-', 1)
    used_numbers[p].add(int(num))
remap = {}
taken = set()
for n in G['nodes']:
    k = key_of[n['id']]
    if k in ledger['ids'] and ledger['ids'][k] not in taken:
        remap[n['id']] = ledger['ids'][k]
        taken.add(remap[n['id']])
new_keys = []
for n in G['nodes']:
    if n['id'] in remap:
        continue
    p = n['id'].rsplit('-', 1)[0]
    num = max(used_numbers[p] | {0}) + 1
    used_numbers[p].add(num)
    nid = f'{p}-{num:03d}'
    remap[n['id']] = nid
    ledger['ids'][key_of[n['id']]] = nid
    new_keys.append(key_of[n['id']])
retired = sorted({v for k, v in ledger['ids'].items() if not k.startswith('catalog:')} - set(remap.values()))  # catalog: keys belong to tools/catalog.py


def sub(x):
    if isinstance(x, str):
        return remap.get(x, x)
    if isinstance(x, list):
        return [sub(v) for v in x]
    if isinstance(x, dict):
        return {k: sub(v) for k, v in x.items()}
    return x


G = sub(G)
A = sub(A)
ledger['ids'] = dict(sorted(ledger['ids'].items()))
with open(LEDGER, 'w', encoding='utf8') as fh:
    json.dump(ledger, fh, indent=1)
    fh.write('\n')

nodes = {n['id']: n for n in G['nodes']}
edges = G['edges']


def add_edge(src, rel, dst, file=None, line=None, note=None):
    edges.append(dict(src=src, rel=rel, dst=dst, file=file, line=line, note=note))


# ------------------------------------------------------------------ 2. documentation nodes
src_files = [f for f in subprocess.run(['git', 'ls-files'], capture_output=True, text=True).stdout.split('\n') if f]
code_files = [f for f in src_files if f.startswith(('apps/', 'packages/', 'tests/', 'scripts/')) and re.search(r'\.(ts|tsx|mjs|js|sql)$', f)]
code_text = {f: read(f) for f in code_files if os.path.exists(f)}

fs_doc = read('docs/reports/FEATURE_STATUS_2026-10-21.md')
doc_status = {}
for m in re.finditer(r'^\| (F-\d{2,3}) \| ([^|]+) \| [^|]* \| [^|]* \| ([^|]+) \|', fs_doc, re.M):
    doc_status[m.group(1)] = m.group(3).strip()
STATUS_MAP = {'Implemented, unverified': 'IMPLEMENTED', 'Partially implemented': 'PARTIALLY_IMPLEMENTED', 'Not implemented': 'NOT_IMPLEMENTED',
              'Broken or regressed': 'BROKEN', 'Deprecated or rejected': 'DEPRECATED'}

reg = 'docs/registries/FEATURE_REGISTRY.md'
reg_t = read(reg)
spec_nodes = []
for i, l in enumerate(reg_t.split('\n'), 1):
    m = re.match(r'^\| (F-\d{2,3}) \| ([^|]+) \| ([^|]*) \| ([^|]*) \| ([^|]*) \| ([^|]*) \|', l)
    if m and m.group(1) not in nodes:
        fid = m.group(1)
        ds = doc_status.get(fid)
        spec_nodes.append(dict(id=fid, type='DOCF', name=m.group(2).strip(), category=m.group(3).strip(), priority=m.group(4).strip(), phase=m.group(5).strip(),
                               doc_status=ds, doc_status_source='docs/reports/FEATURE_STATUS_2026-10-21.md' if ds else None,
                               evidence=[dict(file=reg, line=i, symbol=fid)]))
jreg = 'docs/experience/JOURNEY_REGISTRY.md'
for i, l in enumerate(read(jreg).split('\n'), 1):
    m = re.match(r'^\| (J-\d{2}) \| ([^|]+) \| ([^|]*) \| ([^|]*) \|', l)
    if m and m.group(1) not in nodes and not any(s['id'] == m.group(1) for s in spec_nodes):
        spec_nodes.append(dict(id=m.group(1), type='DOCJ', name=m.group(2).strip(), personas=m.group(3).strip(), terminal=m.group(4).strip(),
                               evidence=[dict(file=jreg, line=i, symbol=m.group(1))]))
breg = 'docs/registries/BUSINESS_RULE_REGISTRY.md'
for i, l in enumerate(read(breg).split('\n'), 1):
    m = re.match(r'^\| (BR-\d{2,3}) \| ([^|]+) \|', l)
    if m and not any(s['id'] == m.group(1) for s in spec_nodes):
        spec_nodes.append(dict(id=m.group(1), type='DOCBR', name=m.group(2).strip()[:160], evidence=[dict(file=breg, line=i, symbol=m.group(1))]))
for s in spec_nodes:
    nodes[s['id']] = s
br_by_num = {int(s['id'][3:]): s['id'] for s in spec_nodes if s['type'] == 'DOCBR'}

# which node stands for a file: the most specific node whose primary evidence is that file
TYPE_RANK = {'SCR': 0, 'COMP': 1, 'TEST': 2, 'SVC': 3, 'MOD': 4, 'INFRA': 5}
file_node = {}
for n in nodes.values():
    t = n['type']
    if t not in TYPE_RANK:
        continue
    for e in n.get('evidence') or []:
        f = e.get('file')
        if f and (f not in file_node or TYPE_RANK[t] < TYPE_RANK[nodes[file_node[f]]['type']]):
            file_node[f] = n['id']
# domain modules are named domain/<x> with evidence on the file
for n in nodes.values():
    if n['type'] == 'MOD' and n.get('kind') == 'domain-module':
        for e in n.get('evidence') or []:
            if e.get('file'):
                file_node.setdefault(e['file'], n['id'])
test_node = {n['name']: n['id'] for n in nodes.values() if n['type'] == 'TEST'}
api_by_key = {n['name']: n['id'] for n in nodes.values() if n['type'] == 'API'}

route_cited = collections.defaultdict(set)
for r in A['routes']:
    for fid in r.get('fids', []):
        if fid in nodes:
            route_cited[fid].add(r['key'])
seen = set()
for fid, keys in route_cited.items():
    for k in sorted(keys):
        aid = api_by_key.get(k)
        if aid and (aid, fid) not in seen:
            seen.add((aid, fid))
            ev = nodes[aid]['evidence'][0]
            add_edge(aid, 'IMPLEMENTS', fid, ev.get('file'), ev.get('line'), 'route handler block cites the documented ID')

ID_RE = re.compile(r'\b(F-\d{2,3}|J-\d{2}|BR-\d{2,3})\b')
unlinked_citations = collections.Counter()
for f, t in sorted(code_text.items()):
    first = {}
    for i, l in enumerate(t.split('\n'), 1):
        for m in ID_RE.finditer(l):
            raw = m.group(1)
            did = br_by_num.get(int(raw[3:])) if raw.startswith('BR-') else raw
            if did and did in nodes and did not in first:
                first[did] = i
    if f == 'apps/api/src/server.ts' or f == 'apps/api/src/billing-stripe.ts':
        continue  # route-level edges above are more precise than a file-level edge
    for did, line in first.items():
        if f in test_node:
            src, rel = did, 'TESTED_BY'
            dst = test_node[f]
            if (src, dst) not in seen:
                seen.add((src, dst)); add_edge(src, rel, dst, f, line, 'test source cites the documented ID')
        elif f in file_node:
            src = file_node[f]
            if (src, did) not in seen:
                seen.add((src, did)); add_edge(src, 'IMPLEMENTS', did, f, line, 'source file cites the documented ID')
        else:
            unlinked_citations[f] += 1

# ------------------------------------------------------------------ 3. execution evidence
# Reports are reduced to quality/EXECUTION_RESULTS.json (relative paths only), which is committed so the
# map can be regenerated without re-running tests. It records the commit it was measured on.
COMPACT = os.path.join(OUT, 'quality', 'EXECUTION_RESULTS.json')
compact = None
if RES and os.path.isdir(RES):
    run = json.load(open(os.path.join(RES, 'run.json'))) if os.path.exists(os.path.join(RES, 'run.json')) else {}
    rel_root = run.get('root')

    def relpath(p):
        if rel_root and p.startswith(rel_root):
            return p[len(rel_root):].lstrip('/')
        m = re.search(r'((?:tests|scripts)/.*)$', p)
        return m.group(1) if m else p

    compact = dict(commit=run.get('commit'), date=run.get('date'), commands=run.get('commands', {}), checks=run.get('checks', []), suites={}, files={}, e2e=[])
    for label in ('vitest', 'vitest-pg'):
        p = os.path.join(RES, f'{label}.json')
        if not os.path.exists(p):
            continue
        d = json.load(open(p))
        suite = dict(total=d.get('numTotalTests'), passed=d.get('numPassedTests'), failed=d.get('numFailedTests'),
                     skipped=(d.get('numPendingTests') or 0) + (d.get('numTodoTests') or 0), files=0)
        for tr in d.get('testResults', []):
            f = relpath(tr['name'])
            c = collections.Counter(a['status'] for a in tr.get('assertionResults', []))
            res = dict(runner=label, passed=c.get('passed', 0), failed=c.get('failed', 0), skipped=c.get('pending', 0) + c.get('skipped', 0) + c.get('todo', 0),
                       failures=[a['fullName'] for a in tr.get('assertionResults', []) if a['status'] == 'failed'][:10])
            if tr.get('status') == 'failed' and not res['failed']:
                res['failed'] = 1
                res['failures'] = [(tr.get('message') or 'file failed to load')[:200]]
            suite['files'] += 1
            compact['files'][f] = res
        compact['suites'][label] = suite
    p = os.path.join(RES, 'node-test.json')  # {"files": {path: {passed, failed, skipped}}}, hand-written from `node --test` TAP totals
    if os.path.exists(p):
        d = json.load(open(p))
        for f, r in d['files'].items():
            compact['files'][f] = dict(runner='node-test', passed=r['passed'], failed=r['failed'], skipped=r.get('skipped', 0), failures=[])
        compact['suites']['node-test'] = dict(total=sum(r['passed'] + r['failed'] + r.get('skipped', 0) for r in d['files'].values()),
                                              passed=sum(r['passed'] for r in d['files'].values()), failed=sum(r['failed'] for r in d['files'].values()),
                                              skipped=sum(r.get('skipped', 0) for r in d['files'].values()), files=len(d['files']))
    p = os.path.join(RES, 'e2e.json')
    if os.path.exists(p):
        d = json.load(open(p))

        def walk(s, file=None):
            file = s.get('file', file)
            for sp in s.get('specs', []):
                outcome = 'passed'
                for t in sp.get('tests', []):
                    sts = [r.get('status') for r in t.get('results', [])]
                    if t.get('status') == 'skipped' or sts == ['skipped']:
                        outcome = 'skipped'
                    elif not sp.get('ok', True) or 'failed' in sts or 'timedOut' in sts:
                        outcome = 'failed'
                compact['e2e'].append(dict(file='tests/e2e/' + os.path.basename(sp.get('file') or file), title=sp['title'], line=sp.get('line'), outcome=outcome))
            for c in s.get('suites', []):
                walk(c, file)
        for s in d.get('suites', []):
            walk(s)
        rs = compact['e2e']
        compact['suites']['e2e'] = dict(total=len(rs), passed=sum(1 for r in rs if r['outcome'] == 'passed'), failed=sum(1 for r in rs if r['outcome'] == 'failed'),
                                        skipped=sum(1 for r in rs if r['outcome'] == 'skipped'), files=len({r['file'] for r in rs}))
        by_file = collections.defaultdict(list)
        for r in rs:
            by_file[r['file']].append(r)
        for f, fr in by_file.items():
            c = collections.Counter(r['outcome'] for r in fr)
            compact['files'][f] = dict(runner='playwright', passed=c.get('passed', 0), failed=c.get('failed', 0), skipped=c.get('skipped', 0),
                                       failures=[r['title'] for r in fr if r['outcome'] == 'failed'][:10])
    compact['files'] = dict(sorted(compact['files'].items()))
    with open(COMPACT, 'w', encoding='utf8') as fh:
        json.dump(compact, fh, indent=1)
        fh.write('\n')
elif os.path.exists(COMPACT):
    compact = json.load(open(COMPACT))

execution = dict(available=False)
if compact:
    execution = dict(available=True, commit=compact.get('commit'), date=compact.get('date'), commands=compact.get('commands', {}), checks=compact.get('checks', []), suites=compact.get('suites', {}),
                     failed_files=sorted(f for f, r in compact['files'].items() if r['failed']), unmatched_files=sorted(f for f in compact['files'] if f not in test_node))
    for f, r in compact['files'].items():
        if f in test_node:
            nodes[test_node[f]]['execution'] = r
    by_file = collections.defaultdict(list)
    for r in compact.get('e2e', []):
        by_file[r['file']].append(r)
    for j in [n for n in nodes.values() if n['type'] == 'JOUR']:
        if '${' in j['title']:  # parameterised title: one source test, several executed instances
            pat = re.compile('^' + '.*'.join(re.escape(x) for x in re.split(r'\$\{[^}]*\}', j['title'])) + '$')
            cands = [r for r in by_file.get(j['spec'], []) if pat.match(r['title'])]
        else:
            cands = [r for r in by_file.get(j['spec'], []) if r['title'] == j['title']]
            if len(cands) > 1:
                cands = [r for r in cands if r['line'] == j['evidence'][0].get('line')] or cands[:1]
        outs_ = {r['outcome'] for r in cands}
        outcome = 'not-matched' if not cands else 'failed' if 'failed' in outs_ else 'passed' if outs_ == {'passed'} else 'skipped'
        j['execution'] = dict(runner='playwright', outcome=outcome, instances=len(cands))
    execution['journeys_matched'] = sum(1 for n in nodes.values() if n['type'] == 'JOUR' and n['execution']['outcome'] != 'not-matched')

G['nodes'] = list(nodes.values())
edges.sort(key=lambda e: (e['src'], e['rel'], e['dst'], str(e['file']), e['line'] or 0, str(e['note'])))
G['edges'] = edges
A['execution'] = execution
A['id_ledger'] = dict(new=len(new_keys), new_keys=new_keys[:50], retired=retired, total=len(ledger['ids']))
A['doc_citations_unlinked_files'] = dict(unlinked_citations)
json.dump(G, open(f'{SCR}/graph_raw.json', 'w'))
json.dump(A, open(f'{SCR}/aux.json', 'w'))
print('enrich ok:', len(spec_nodes), 'documentation nodes;', sum(1 for e in edges if e['rel'] == 'IMPLEMENTS'), 'IMPLEMENTS edges;',
      len(new_keys), 'new IDs;', len(retired), 'retired IDs; execution', 'attached' if execution['available'] else 'not supplied')
